function getAudioDurationSeconds(filePath) {
  const output = execFileSync(
    "ffprobe",
    [
      "-v",
      "error",
      "-show_entries",
      "format=duration",
      "-of",
      "default=noprint_wrappers=1:nokey=1",
      filePath,
    ],
    { encoding: "utf8" },
  ).trim();

  return Number.parseFloat(output);
}

function generateSceneAudio(scene) {
  const mp3Path = join(OUT_DIR, `${scene.id}.mp3`);

  console.log(`Generating ${scene.id}...`);

  const result = spawnSync(
    "edge-tts",
    [
      "--voice",
      VOICE,
      "--text",
      scene.text,
      "--write-media",
      mp3Path,
      "--rate",
      "+5%",
    ],
    { encoding: "utf8" },
  );

  if (result.status !== 0) {
    throw new Error(
      `edge-tts failed for ${scene.id}: ${result.stderr || result.stdout}`,
    );
  }

  const durationInSeconds = getAudioDurationSeconds(mp3Path);

  return {
    id: scene.id,
    file: `voiceover/product-demo/${scene.id}.mp3`,
    durationInSeconds,
    durationInFrames: Math.ceil(
      (durationInSeconds + PADDING_SECONDS) * 30,
    ),
  };
}

mkdirSync(OUT_DIR, { recursive: true });

if (!spawnSync("edge-tts", ["--version"], { encoding: "utf8" }).stdout) {
  console.error(
    "edge-tts is required. Install with: pip install edge-tts",
  );
  process.exit(1);
}

const manifest = {
  fps: 30,
  voice: VOICE,
  paddingSeconds: PADDING_SECONDS,
  scenes: SCENES.map(generateSceneAudio),
  generatedAt: new Date().toISOString(),
};

writeFileSync(
  join(OUT_DIR, "manifest.json"),
  `${JSON.stringify(manifest, null, 2)}\n`,
);

