#!/usr/bin/env node
/**
 * Generate / refresh TypeScript contract method list from Rust exports.
 * Full `stellar contract bindings typescript` is used when the CLI + WASM exist;
 * otherwise we sync method names from contract/src/lib.rs into packages/stellar/src/generated/methods.ts.
 */
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { execFileSync } from 'node:child_process';

const rust = readFileSync('contract/src/lib.rs', 'utf8');
const methods = [...rust.matchAll(/pub\s+fn\s+(\w+)\s*\(/g)].map((m) => m[1]);
const unique = [...new Set(methods)];

mkdirSync('packages/stellar/src/generated', { recursive: true });
const out = `/**
 * AUTO-GENERATED by scripts/generate-bindings.mjs — do not edit by hand.
 */
export const CONTRACT_METHODS = ${JSON.stringify(unique, null, 2)} as const;

export type ContractMethod = (typeof CONTRACT_METHODS)[number];
`;
writeFileSync('packages/stellar/src/generated/methods.ts', out);
console.log('Wrote packages/stellar/src/generated/methods.ts:', unique.join(', '));

const wasm = 'contract/target/wasm32v1-none/release/contract.wasm';
try {
  execFileSync('stellar', ['--version'], { stdio: 'ignore' });
  if (existsSync(wasm)) {
    execFileSync(
      'stellar',
      [
        'contract',
        'bindings',
        'typescript',
        '--wasm',
        wasm,
        '--output-dir',
        'packages/stellar/src/generated/client',
        '--overwrite',
      ],
      { stdio: 'inherit' },
    );
    console.log('Generated stellar TS client under packages/stellar/src/generated/client');
  } else {
    console.log('WASM not built — skipped full bindings client (method list still updated).');
  }
} catch {
  console.log('stellar CLI unavailable — method list sync only.');
}
